let a = 5;
let b = 2;

console.log("a =", a, "&", "b =", b);


console.log("a + b =", a + b);
console.log("a - b =", a - b);
console.log("a * b =", a * b);
console.log("a / b =", a / b);
console.log("a % b =", a % b);
console.log("a ** b =", a ** b);

// Unary Operator
{
    let a = 5;
    let b = 4;

    console.log("a =", a, "&", "b =", b);

    console.log("a++ =", a++);
    console.log("a =", a);
    console.log("++a =", ++a);
    console.log("a =", a);
    console.log("b-- =", b--);
    console.log("b =", b);
    console.log("--b =", --b);
    console.log("b =", b);
}
